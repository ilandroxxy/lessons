    n3 = convert(n, 3)
    if n % 3 == 0:
        n3 = '1' + n3 + '02'
    else:
        x = (n % 3) * 4
        n3 = n3 + convert(x, 3)
    r = int(n3, 3)
    if r < 250:
        RES.append(r)
