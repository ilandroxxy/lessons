# б) если сумма цифр троичной записи числа не кратна 9, то к этой записи справа
# дописывается троичная запись остатка от деления суммы цифр записи на 9;
# Полученная таким образом запись является троичной записью искомого числа R.
# 3. Результат переводится в десятичную систему и выводится на экран.

# Укажите минимальное число R, которое может быть результатом работы данного алгоритма,
# при условии, что N больше 166.

alp = sorted('0123456789QWERTYUIOPASDFGHJKLZXCVBNM')


def convert(n, b):
    r = ''
    while n > 0:
        r = alp[n % b] + r
        n //= b
    return r


RES = []
for n in range(1, 10000):
    n3 = convert(n, 3)
    if sum(map(int, n3)) % 9 == 0:
        n3 = n3 + '2'
    else:
        n3 = n3 + convert(sum(map(int, n3)) % 9, 3)
