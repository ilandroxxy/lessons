# № 31417 (Уровень: Средний)
# A. Прибавь 1
# B. Допиши сумму
# Вторая команда применяется только к числу,
# сумма цифр которого меньше 10, и действует,
# дописывая эту сумму цифр справа.

# Сколько существует программ, для которых при
# исходном числе 3 результатом является число 200?

def f(a, b):
    if a == b:
        return 1
    if a > b:
        return 0

    summa = sum([int(x) for x in str(a)])
    if summa < 10:
        return f(a + 1, b) + f(int(str(a) + str(summa)), b)
    else:
        return f(a + 1, b)


print(f(3, 200))



