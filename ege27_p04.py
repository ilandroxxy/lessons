# Базовая арифметкиа

a, b = 7, 2

print(a + b)
print(a - b)
print(a * b)

print()  # В каждой функции print() есть переход на новую строку \n

# Три типа делений в python
print(a / b)  # 3.5 - Обыкновенное вещественное деление - резултьтат всегда float()
print(a // b)  # 3 - Взятие только целой части от деления (убирается остаток) - результат всегда int()
print(a % b)   # 1 - Взятие остатка от деления - результат всегда int()


n = 436
print(n // 10)  # 43
print(n % 10)  # 6 - взятие последней цифры числа

print(n // 100)  # 4
print(n % 100)  # 36 - взятие двух последних цифр числа

print(n % 1000)  # 436 - взятие трех последних цифр числа


print(n % 2 == 0)  # - Число делится на 2 | Число кратно 2 | Число четное
print(n % 2 != 0)  # - Число не делится на 2 | Число не кратно 2 | Число нечетное

print(n % 27 == 0)  # - Число делится на 27 | Число кратно 27


print(f'Возведение в степень: {2 ** 4}')  # 16
print(f'Взятие квадратного корня: {16 ** (1 / 2)}')  # 4.0
print(f'Взятие кубического корня: {27 ** (1 / 3)}')  # 3.0





