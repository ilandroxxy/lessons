# Срезы списков
'''
# i   0    1    2    3    4
L = ['a', 'b', 'c', 'd', 'e']   # list (списки)
# -i -5   -4   -3   -2   -1

print(L[2:4])  # ['c', 'd']
print(L[:4])  # ['a', 'b', 'c', 'd']
print(L[2:])  # ['c', 'd', 'e']

print(L[2:])  #  - все элементы кроме первых двух
print(L[:2])  # - первые два элемента
print(L[-2:])  # - последние два элемента
print(L[1:-1])   # - все элементы кроме первого и последнего

print(L[0::2])  # ['a', 'c', 'e'] - все элементы под четными индексами
print(L[1::2])  # ['b', 'd'] - все элементы под нечетными индексами

print(L[::-1])  # ['e', 'd', 'c', 'b', 'a'] - разворот в обратном порядке

alp = sorted('0123456789QWERTYUIOPASDFGHJKLZXCVBNM')
print(alp[:2])  # ['0', '1']
print(alp[:8])  # ['0', '1', '2', '3', '4', '5', '6', '7']

print(alp[0::2])  # ['0', '2', '4', '6', '8', 'A', 'C', 'E', 'G', 'I', 'K', 'M', 'O', 'Q', 'S', 'U', 'W', 'Y']
print(alp[1::2])  # ['1', '3', '5', '7', '9', 'B', 'D', 'F', 'H', 'J', 'L', 'N', 'P', 'R', 'T', 'V', 'X', 'Z']

s = 'abcde'
print(s[2:4])  # cd
print(s[1:-1])  # bcd
print(s[::-1])  # edcba
'''



# Функции списков
'''
M = [2, 1, 2, 3, 2, 3]

print(len(M))  # - возвращает кол-во элементов в списке
print(sum(M))  # - возвращает сумму элементов списка
print(max(M), min(M))

print(sorted(M))  # [1, 2, 2, 2, 3, 3]  - сортирует по возрастанию
print(sorted(M)[::-1])  # [3, 3, 2, 2, 2, 1] - сортирует по убыванию 

print(set(M))  # {1, 2, 3} - убирает копии элементов 
'''

