# у числа нет, то значение M считается равным нулю.

# Напишите программу, которая перебирает целые числа, бо́льшие 5 700 000,
# в порядке возрастания и ищет среди них такие, для которых M больше 70 000
# и является полным квадратом натурального числа. В ответе запишите в первом
# столбце таблицы первые пять найденных чисел в порядке возрастания,
# а во втором столбце – соответствующие им значения M.

def divisors(x):
    d = []
    for j in range(2, int(x**0.5)+1):  # не считая самого числа
        if x % j == 0:
            d += [j, x // j]
    return sorted(set(d))

cnt = 0
for x in range(5_700_000+1, 10**10):
    d = [j for j in divisors(x) if len(divisors(j)) == 0]
    if len(d) > 0:
        M = (min(d) + max(d))
        if M > 70_000 and (M ** 0.5) == int(M ** 0.5):
            cnt += 1
            print(x, M)
            if cnt == 5:
                break

