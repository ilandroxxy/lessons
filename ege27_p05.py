# Сколько существует программ, для которых при исходном
# числе 100 результатом является число 141?

def F(a, b):
    if a >= b:
        return a == b
    s = str(a)
    if s[1] < s[2]:
        return F(a + 1, b) + F(int(s[0] + s[2] + s[1]), b)
    else:
        return F(a + 1, b)

print(F(100, 141))


