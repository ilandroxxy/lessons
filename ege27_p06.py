# № 9792 Основная волна 20.06.23(Уровень: Базовый)
# Назовём маской числа последовательность цифр, в которой также могут встречаться следующие символы:
# — символ «?» означает ровно одну произвольную цифру;
# — символ «*» означает любую последовательность цифр произвольной длины;
# в том числе «*» может задавать и пустую последовательность.

# Среди натуральных чисел, не превышающих 10**8, найдите все числа,
# соответствующие маске 1*2??76, делящиеся на 1923 без остатка.
# В ответе запишите в первом столбце таблицы все найденные числа в порядке возрастания,
# а во втором столбце — соответствующие им результаты деления этих чисел на 1923.
'''
from fnmatch import *
for x in range(1923, 10**8, 1923):
    if fnmatch(str(x), '1*2??76'):
        print(x, x // 1923)

# Решение номер 2 через библиотеку re

from re import *
for x in range(1923, 10**8, 1923):
    if fullmatch('1[0-9]*2[0-9][0-9]76', str(x)):
        print(x, x // 1923)
'''

