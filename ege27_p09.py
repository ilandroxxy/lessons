# 🌐 Шпаргалка по компьютерным сетям для №10 ЕГЭ #tpy
# ⠀
# 🚩 1. Что такое IP-адрес?
# ⠀
# IP-адрес узла в формате IPv4 состоит из 4 байтов (32 бит).
# Каждый байт содержит 8 бит и принимает значения от 0 до 255.
# ⠀
# Пример IP-адреса: 214.120.249.18
# ⠀
# Каждое число можно перевести в двоичную систему счисления:
'''
print(f'{214:08b}')  # 11010110
print(f'{120:08b}')  # 01111000
print(f'{249:08b}')  # 11111001
print(f'{18:08b}')   # 00010010
'''
# 📎 Запись 08b означает перевод в двоичную систему
# с дополнением числа нулями слева до 8 бит.



# 🚩 2. Как определить адрес сети?
#
# Дано:
# Узел сети: 214.120.249.18
# Маска сети: 255.255.240.0
#
# Адрес сети получается с помощью побитовой операции И (&)
# между IP-адресом узла и маской сети.

# Адрес сети = Узел сети & Маска сети
#
# Вспомним таблицу истинности для and:
# 0 and 0  # 0
# 0 and 1  # 0
# 1 and 0  # 0
# 1 and 1  # 1
#
# Операция возвращает 1 только тогда, когда оба бита равны 1.
'''
print(214 & 255)  # 214
'''


# 🧑‍💻 Переведём адрес и маску в двоичную систему:
'''
knot = [214, 120, 249, 18]
mask = [255, 255, 240, 0]

print('.'.join(f'{x:08b}' for x in knot))
print('.'.join(f'{x:08b}' for x in mask))
'''

# Результат:
# 11010110.01111000.11111001.00010010
# 11111111.11111111.11110000.00000000
# ⠀
# Выполняем операцию И для каждого бита и получаем:
# ⠀
# 11010110.01111000.11110000.00000000
# ⠀
# Теперь переведём полученные байты обратно в десятичную систему.
'''
print(int('11010110', 2))  # 214
print(int('01111000', 2))  # 120
print(int('11110000', 2))  # 240
print(int('00000000', 2))  # 0
'''
# ✅ Ответ: 214.120.240.0




# 🚩 3. Как решить задачу быстрее?
# ⠀
# В Python есть оператор &, который позволяет сразу выполнить побитовое И для двух чисел. Поэтому переводить каждый байт вручную необязательно!
'''
print(214 & 255)  # 214
print(120 & 255)  # 120
print(249 & 240)  # 240
print(18 & 0)     # 0

# А если хочется получить готовый адрес сети:

ip = [214, 120, 249, 18]
mask = [255, 255, 240, 0]

net = [a & b for a, b in zip(ip, mask)]

print(*net, sep='.')
# 214.120.240.0
'''



# 🚩 4. Почему маску можно записать как /20?
'''⠀
# Маска сети в двоичной системе состоит из последовательности единиц, после которых идут только нули. Количество единиц определяет длину префикса сети.
# ⠀
# Наша маска 255.255.240.0 выглядит так:
# ⠀
# 11111111.11111111.11110000.00000000
# ⠀
# Считаем единицы:
# 8 + 8 + 4 = 20
# ⠀
# Поэтому маску можно записать двумя способами:
# ⠀
# 255.255.240.0 или /20
# ⠀
# Проверим через Python:
# ⠀
# mask = '1' * 20 + '0' * (32 - 20)
# print(mask)
#
# # 11111111111111111111000000000000
'''


