# for n in range(1, 33):
#     mask = '1' * n + '0' * (32 - n)
#     print(n, mask)
# ⠀
# Пример нескольких масок:
# ⠀
# /1  10000000000000000000000000000000
# /2  11000000000000000000000000000000
# /3  11100000000000000000000000000000
# ...
# /20 11111111111111111111000000000000
# ...
# /32 11111111111111111111111111111111
# ⠀
# 📎 Для полного перебора префиксов IPv4 от /0 до /32 можно использовать range(33).
